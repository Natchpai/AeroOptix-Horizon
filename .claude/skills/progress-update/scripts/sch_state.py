#!/usr/bin/env python3
"""Generate the schematic state record from KiCad's own netlist.

Read-only on the design. Python 3.10+ standard library only. Prints Markdown,
or writes it with --out: one table per sheet (references grouped by value,
MFR.P/N, LCSC, DNP and STATUS) and the nets that leave the sheet. The spec
keeps the reasons and decision IDs and links here instead of copying parts.

Usage:
    python -I sch_state.py --project <root.kicad_sch> [--out <md>] [--netlist <xml>]

The netlist comes from the sibling sch-inspect skill (kicad-cli on a temp
copy of the saved files), or from --netlist.
"""
from __future__ import annotations

import argparse
import datetime as dt
import importlib.util
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.dont_write_bytecode = True
QUERY = Path(__file__).resolve().parents[2] / "sch-inspect" / "scripts" / "query_sch.py"
COLUMNS = ("value", "MFR.P/N", "LCSC", "dnp", "STATUS")


def query_module():
    if not QUERY.is_file():
        raise RuntimeError("sch-inspect skill not installed; pass --netlist")
    spec = importlib.util.spec_from_file_location("_sch_inspect_query", QUERY)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def ref_key(ref: str):
    m = re.fullmatch(r"([A-Za-z_#]*)(\d+)(.*)", ref)
    return (m.group(1), int(m.group(2)), m.group(3)) if m else (ref, -1, "")


def compress(refs: list[str]) -> str:
    """R901, R902, R903, R905 -> R901 to R903, R905."""
    out, run = [], []
    for r in sorted(refs, key=ref_key):
        k = ref_key(r)
        if run and k[1] >= 0 and k[0] == ref_key(run[-1])[0] and k[1] == ref_key(run[-1])[1] + 1 and not k[2]:
            run.append(r)
            continue
        if run:
            out.append(run[0] if len(run) == 1 else f"{run[0]} to {run[-1]}" if len(run) > 2 else ", ".join(run))
        run = [r]
    if run:
        out.append(run[0] if len(run) == 1 else f"{run[0]} to {run[-1]}" if len(run) > 2 else ", ".join(run))
    return ", ".join(out)


def cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ") or "-"


def render(parts: dict, nets: list, source: str, today: str) -> str:
    by_sheet = defaultdict(list)
    for ref, p in parts.items():
        by_sheet[p["sheet"]].append(ref)
    leaving = defaultdict(set)
    for n in nets:
        sheets = {parts[x["reference"]]["sheet"] for x in n["nodes"] if x["reference"] in parts}
        if len(sheets) > 1:
            for s in sheets:
                leaving[s].add(n["net_name"].rsplit("/", 1)[-1])
    lines = ["# Schematic State (generated)", "",
             f"Generated by `sch_state.py` on {today} from {source}. Do not edit by hand: run the "
             "script again. It records what is drawn, not what is decided; decisions and reasons "
             "live in the specification.", ""]
    for sheet in sorted(by_sheet):
        refs = by_sheet[sheet]
        lines += [f"## {sheet.strip('/') or '/'} ({len(refs)} parts)", "",
                  "| References | Value | MFR.P/N | LCSC | DNP | STATUS |", "|---|---|---|---|---|---|"]
        groups = defaultdict(list)
        for r in refs:
            groups[tuple(parts[r][c] for c in COLUMNS)].append(r)
        for key, rs in sorted(groups.items(), key=lambda kv: ref_key(min(kv[1], key=ref_key))):
            value, mpn, lcsc, dnp, status = key
            lines.append(f"| {cell(compress(rs))} | {cell(value)} | {cell(mpn)} | {cell(lcsc)} | "
                         f"{'DNP' if dnp else '-'} | {cell(status)} |")
        if leaving[sheet]:
            lines += ["", "Nets to other sheets: " + ", ".join(f"`{n}`" for n in sorted(leaving[sheet])) + "."]
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--project", required=True, help="root .kicad_sch")
    ap.add_argument("--out", help="write the Markdown here instead of stdout")
    ap.add_argument("--netlist", help="read this KiCad XML netlist instead of running kicad-cli")
    args = ap.parse_args()
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    root = Path(args.project).resolve()
    try:
        q = query_module()  # the netlist parser lives in sch-inspect
        if args.netlist:
            text = Path(args.netlist).read_text(encoding="utf-8")
            source = f"the netlist `{Path(args.netlist).name}`"
        else:
            data, _, _ = q.discover(root, 1000)
            text = q.export_netlist(root, q.find_kicad_cli(), [d["file"] for d in data])
            saved = dt.datetime.fromtimestamp(max(Path(d["file"]).stat().st_mtime for d in data))
            source = f"the saved schematic (newest sheet saved {saved:%Y-%m-%d %H:%M})"
        md = render(q.parse_netlist_parts(text), q.parse_netlist(text)[1], source, f"{dt.date.today():%Y-%m-%d}")
    except Exception as exc:  # report, never a traceback
        print(f"NOT_VERIFIED: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 2
    if args.out:
        Path(args.out).write_text(md, encoding="utf-8")
    else:
        print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
