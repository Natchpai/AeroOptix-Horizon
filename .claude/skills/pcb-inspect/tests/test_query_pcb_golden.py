#!/usr/bin/env python3
"""Opt-in real-project golden checks for query_pcb.py (KiCad 10).

Set KICAD_PCB_GOLDEN_BOARD to the absolute path of 2Phase_SynchBuck.kicad_pcb.
Run: python .claude/skills/pcb-inspect/tests/run_tests.py --pattern test_query_pcb_golden.py --label golden
Read-only: hashes the configured board before/after running the query CLI.

The expected values below are documented in
references/2phase-synchbuck-golden-evidence.md and were transcribed from native
PCB text, not generated by query_pcb.py. They are scoped regression evidence,
not complete KiCad PCB Editor parity.
"""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import unittest


SCRIPT = Path(__file__).resolve().parents[1] / 'scripts' / 'query_pcb.py'
BOARD_ENV = 'KICAD_PCB_GOLDEN_BOARD'
USB_NET = '/Top/Power Supplies/+5VUSB'


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


class KiCadPcbGoldenTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        raw_board = os.environ.get(BOARD_ENV, '').strip()
        cls.configured = bool(raw_board)
        cls.board = Path(raw_board).expanduser().resolve() if cls.configured else None
        cls.configuration_error = None
        if not cls.configured:
            return
        if not cls.board.is_file() or cls.board.suffix.lower() != '.kicad_pcb':
            cls.configuration_error = f'Invalid PCB board: {cls.board}'
            return
        if not SCRIPT.is_file():
            cls.configuration_error = f'Missing script: {SCRIPT}'
            return
        cls.before = sha256(cls.board)

    def setUp(self):
        if not self.configured:
            self.skipTest(f'{BOARD_ENV} is not configured')
        if self.configuration_error:
            self.fail(self.configuration_error)

    @classmethod
    def tearDownClass(cls):
        if not cls.configured or cls.configuration_error:
            return
        if sha256(cls.board) != cls.before:
            raise AssertionError('PCB board content changed during query tests')

    def query(self, command, *args):
        process = subprocess.run(
            [sys.executable, str(SCRIPT), command, *args, '--board', str(self.board), '--limit', '200'],
            capture_output=True, text=True, encoding='utf-8', errors='replace',
            timeout=120, check=False, cwd=str(self.board.parent))
        self.assertEqual(process.returncode, 0,
                         f'{command} failed (rc={process.returncode}): {process.stderr}')
        try:
            obj = json.loads(process.stdout)
        except json.JSONDecodeError as exc:
            self.fail(f'{command} returned invalid JSON: {exc}: {process.stdout[:400]}')
        return obj

    def test_r313_native_pad_geometry_and_distance(self):
        pads = self.query('pads', 'R313')
        self.assertEqual(pads.get('status'), 'FOUND')
        self.assertEqual(pads.get('pad_count'), 2)
        self.assertFalse(pads.get('pads_truncated'))
        self.assertEqual(pads['footprint']['position'], {
            'x_mm': 127.5, 'y_mm': 117.25, 'rotation_deg': 0.0,
        })
        expected = {
            '1': {'position': {'x_mm': 126.675, 'y_mm': 117.25}, 'size_mm': {'x_mm': 0.8, 'y_mm': 1.0}},
            '2': {'position': {'x_mm': 128.325, 'y_mm': 117.25}, 'size_mm': {'x_mm': 0.8, 'y_mm': 1.0}},
        }
        actual = {pad['number']: pad for pad in pads['pads']}
        for number, expected_pad in expected.items():
            with self.subTest(pad=number):
                self.assertEqual(actual[number]['position'], expected_pad['position'])
                self.assertEqual(actual[number]['size_mm'], expected_pad['size_mm'])
                self.assertEqual(actual[number]['geometry_status'], 'STRUCTURAL_EVIDENCE')

        distance = self.query('pad-distance', 'R313.1', 'R313.2')
        self.assertEqual(distance.get('status'), 'FOUND')
        self.assertEqual(distance.get('distance_mm'), 1.65)
        self.assertEqual(distance.get('distance_status'), 'STRUCTURAL_EVIDENCE')

    def test_usb_routing_matches_native_segment_and_via_evidence(self):
        tracks = self.query('tracks', USB_NET)
        self.assertEqual(tracks.get('status'), 'FOUND')
        self.assertEqual(tracks.get('net_status'), 'ASSIGNED_WITHOUT_DECLARATION')
        self.assertEqual(tracks.get('track_count'), 18)
        self.assertFalse(tracks.get('tracks_truncated'))
        first = tracks['tracks'][0]
        self.assertEqual(first['geometry_type'], 'segment')
        self.assertEqual(first['start'], {'x_mm': 111.1, 'y_mm': 117.95})
        self.assertEqual(first['end'], {'x_mm': 116.8, 'y_mm': 117.95})
        self.assertEqual(first['layer'], 'F.Cu')
        self.assertEqual(first['width_mm'], 0.3)
        self.assertEqual(first['length_mm'], 5.7)
        self.assertEqual(first['length_status'], 'STRUCTURAL_EVIDENCE')

        vias = self.query('vias', USB_NET)
        self.assertEqual(vias.get('status'), 'FOUND')
        self.assertEqual(vias.get('via_count'), 1)
        self.assertFalse(vias.get('vias_truncated'))
        via = vias['vias'][0]
        self.assertEqual(via['position'], {'x_mm': 111.1, 'y_mm': 117.95})
        self.assertEqual(via['size_mm'], 0.8)
        self.assertEqual(via['drill_mm'], 0.4)
        self.assertEqual(via['layer_span'], ['F.Cu', 'B.Cu'])
        self.assertIsNone(via['via_type'])
        self.assertEqual(via['via_type_status'], 'NOT_VERIFIED')


if __name__ == '__main__':
    unittest.main()
